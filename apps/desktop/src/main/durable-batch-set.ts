import {lstatSync} from 'node:fs';
import {mkdir,open} from 'node:fs/promises';
import {dirname,isAbsolute,join,resolve} from 'node:path';
import {createRepairTaskQueue,type RepairTaskSnapshot} from '../../../../packages/scan-service/src/repair-task-queue.ts';
import {openRepairCheckpointStore} from '../../../../packages/scan-service/src/repair-checkpoint-store.ts';
import {reserveManagedScriptWrites} from './managed-script-lease.ts';

const UUID=/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const SCRIPT=/^[A-Za-z0-9_-]{1,64}$/;
const MAX_ITEMS=64;

export interface TrustedManagedBatchItem{
 /** Unique per-script approval generated by trusted Main; never received as a callback from the renderer. */
 readonly approvalId:string;
 readonly scriptId:string;
 readonly approved:boolean;
 readonly preflight:()=>boolean|Promise<boolean>;
 /** Trusted Main callback writing only a separately reviewed managed revision. */
 readonly write:()=>Promise<unknown>;
}
export interface ManagedBatchCounts{
 readonly queued:number;readonly running:number;readonly completed:number;
 readonly failed:number;readonly blocked:number;readonly cancelled:number;
}
export interface ManagedBatchControls{
 readonly cancel:()=>void;readonly pause:()=>boolean;readonly resume:()=>void;
}
function count(snapshot:RepairTaskSnapshot):ManagedBatchCounts{
 const counts:{-readonly [K in keyof ManagedBatchCounts]:number}={
  queued:0,running:0,completed:0,failed:0,blocked:0,cancelled:0,
 };
 for(const row of snapshot.items)counts[row.status]++;
 return Object.freeze(counts);
}
function assertTrustedAncestors(directory:string):void{
 for(let part=resolve(directory);;part=dirname(part)){
  const meta=lstatSync(part);
  if(!meta.isDirectory()||meta.isSymbolicLink())
   throw new Error('Unsafe durable multi-batch directory');
  const parent=dirname(part);
  if(parent===part)return;
 }
}
/**
 * Main-owned, bounded, offline, serial execution of multiple **individually**
 * and freshly approved managed-revision callbacks. No renderer IPC is exposed.
 *
 * An exclusively reserved group SQLite journal stores only opaque job digests
 * and finite states, and is never reused even if it is empty or failed.
 * Recovery is read-only and fail-closed; no old approval is ever replayed.
 *
 * Each job revalidates its own approval/source hash/backup via a trusted Main
 * preflight immediately before dispatch. No real source userscript is run or
 * written by this executor; the caller supplies ONLY managed-write callbacks.
 */
export async function executeDurableApprovedBatchSet(input:{
 readonly dataRoot:string;
 readonly groupId:string;
 readonly items:readonly TrustedManagedBatchItem[];
 /** False (default): failure of one script must not poison unrelated scripts. */
 readonly stopOnFailure?:boolean;
 /** Receives ONLY status counts; cannot read script names or approval IDs. */
 readonly onProgress?:(counts:ManagedBatchCounts)=>void;
 /** Trusted Main-only control lease. It neither returns nor grants approval. */
 readonly onRegisterControls?:(controls:ManagedBatchControls)=>(()=>void);
}):Promise<ManagedBatchCounts>{
 if(!input||typeof input!=='object'||Array.isArray(input)||
    typeof input.dataRoot!=='string'||!isAbsolute(input.dataRoot)||input.dataRoot.length>4096||
    typeof input.groupId!=='string'||!UUID.test(input.groupId)||
    !Array.isArray(input.items)||input.items.length<1||input.items.length>MAX_ITEMS||
    (input.stopOnFailure!==undefined&&typeof input.stopOnFailure!=='boolean')||
    (input.onProgress!==undefined&&typeof input.onProgress!=='function')||
    (input.onRegisterControls!==undefined&&typeof input.onRegisterControls!=='function'))
  throw new Error('Invalid or unapproved durable multi-batch request');
 const approvedIds=new Set<string>(),scripts=new Set<string>();
 const reviewed=input.items.map(item=>{
  if(!item||typeof item!=='object'||Array.isArray(item)||
     typeof item.approvalId!=='string'||!UUID.test(item.approvalId)||
     typeof item.scriptId!=='string'||!SCRIPT.test(item.scriptId)||
     item.approved!==true||
     typeof item.preflight!=='function'||typeof item.write!=='function'||
     approvedIds.has(item.approvalId.toLowerCase())||scripts.has(item.scriptId))
   throw new Error('Invalid duplicate or unapproved managed repair task identity');
  // UUID identity is case-insensitive: two spellings must not reuse one approval.
  approvedIds.add(item.approvalId.toLowerCase());scripts.add(item.scriptId);
  return Object.freeze({
   approvalId:item.approvalId,scriptId:item.scriptId,
   // Preserve the trusted Main approval source so later revocation is live.
   approvalSource:item,preflight:item.preflight,write:item.write,
  });
 });
 // Acquire all script leases synchronously, before the first await. Refuse
 // a second concurrently active group that could touch the same managed
 // source, even when that group has a different freshly approved UUID.
 const releaseManagedScripts=reserveManagedScriptWrites(input.dataRoot,reviewed.map(row=>row.scriptId));
 try{
 const stopOnFailure=input.stopOnFailure===true;
 const onProgress=input.onProgress;
 const onRegisterControls=input.onRegisterControls;
 assertTrustedAncestors(input.dataRoot);
 const folder=join(input.dataRoot,'repair-queue');
 await mkdir(folder,{recursive:true});
 assertTrustedAncestors(folder);
 const destination=join(folder,input.groupId+'.sqlite');
 // Atomic across processes; old/partially-created group is never reopened
 // for execution. Never delete a checkpoint to reauthorize its original jobs.
 try{
  const reservation=await open(destination,'wx',0o600);
  await reservation.close();
 }catch{
  throw new Error('Durable multi-batch checkpoint unavailable; fresh review required');
 }
 const store=openRepairCheckpointStore(destination);
 let release:()=>void=()=>{};
 try{
  let cancelledForFailure=false;
  const byId=new Map(reviewed.map(row=>[row.approvalId,row]));
  let queue!:ReturnType<typeof createRepairTaskQueue>;
  queue=createRepairTaskQueue(reviewed.map(row=>({
   id:row.approvalId,scriptId:row.scriptId,
   // The queue re-checks this live approval after async preflight and after
   // checkpoint persistence, immediately before dispatching a managed write.
   get approved(){return row.approvalSource.approved===true;},
   execute:row.write,
  })),{
   beforeDispatch:async row=>{
    const operation=byId.get(row.id);
    if(!operation||operation.approvalSource.approved!==true)return false;
    try{
     const verified=await operation.preflight();
     return verified===true&&operation.approvalSource.approved===true;
    }catch{return false;}
   },
   onCheckpoint:state=>store.save(state),
   onProgress:state=>{
    if(stopOnFailure&&!cancelledForFailure&&
       state.items.some(row=>row.status==='failed'||row.status==='blocked')){
     cancelledForFailure=true;
     queue.cancel();
    }
    try{onProgress?.(count(state));}catch{}
   },
  });
  if(onRegisterControls){
   let detached:()=>void;
   try{
    detached=onRegisterControls(Object.freeze({
     cancel:()=>queue.cancel(),pause:()=>queue.pause(),resume:()=>queue.resume(),
    }));
   }catch{
    // Registration callbacks are trusted, but their thrown messages are not
    // guaranteed free of user-private source or filesystem context.
    throw new Error('Native multi-batch control registration failed; fresh review required');
   }
   if(typeof detached!=='function')throw new Error('Invalid Main multi-batch control lease');
   release=detached;
  }
  // A trusted Main control may cancel synchronously while registering,
  // before run() starts. Persist that terminal snapshot explicitly; run()
  // deliberately refuses to restart an already cancelled queue.
  if(queue.snapshot().cancelled){
   await store.save(queue.checkpoint());
   return count(queue.snapshot());
  }
  const final=await queue.run();
  return count(final);
 }finally{
  // Both resources must be released regardless of an observer callback
  // failure. Never expose a Main control cleanup exception containing
  // private identity, source or path information to the renderer.
  let cleanupFailed=false;
  try{release();}catch{cleanupFailed=true;}
  try{store.close();}catch{cleanupFailed=true;}
  if(cleanupFailed)throw new Error('Durable multi-batch cleanup failed; fresh review required');
 }
 }finally{
  // Always release group ownership after success, failure, cancellation,
  // interrupted reservation, or a fail-closed preflight. Never abandon the
  // lock just because SQLite or a trusted caller raises an exception.
  releaseManagedScripts();
 }
}
